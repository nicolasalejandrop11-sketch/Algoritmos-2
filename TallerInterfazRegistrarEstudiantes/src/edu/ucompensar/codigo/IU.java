    private void btnCalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularActionPerformed
        try {
            // 1. Validar campos vacíos
            if (txtCodigo.getText().trim().isEmpty()
                    || txtNombre.getText().trim().isEmpty()
                    || txtNota1.getText().trim().isEmpty()
                    || txtNota2.getText().trim().isEmpty()
                    || txtNota3.getText().trim().isEmpty()) {

                JOptionPane.showMessageDialog(this, "Por favor complete todos los campos del formulario.", "Campos incompletos", JOptionPane.WARNING_MESSAGE);
                return;
            }

            // 2. Capturar datos de texto
            String codigo = txtCodigo.getText().trim();
            String nombre = txtNombre.getText().trim();

            // 3. Convertir y validar notas a números
            double nota1 = Double.parseDouble(txtNota1.getText().trim());
            double nota2 = Double.parseDouble(txtNota2.getText().trim());
            double nota3 = Double.parseDouble(txtNota3.getText().trim());

            // Validar rango (0.0 a 5.0)
            if (nota1 < 0.0 || nota1 > 5.0 || nota2 < 0.0 || nota2 > 5.0 || nota3 < 0.0 || nota3 > 5.0) {
                JOptionPane.showMessageDialog(this, "Las notas deben estar dentro del rango de 0.0 a 5.0.", "Rango inválido", JOptionPane.ERROR_MESSAGE);
                return;
            }

            // 4. Calcular nota definitiva (30%, 30%, 40%)
            double definitiva = (nota1 * 0.30) + (nota2 * 0.30) + (nota3 * 0.40);

            // 5. Determinar estado (Aprobado >= 3.0)
            String estado = (definitiva >= 3.0) ? "Aprobado" : "Reprobado";

            // 6. Agregar los datos a la tabla
            DefaultTableModel model = (DefaultTableModel) tblEstudiantes.getModel();
            model.addRow(new Object[]{
                codigo,
                nombre,
                String.format("%.2f", nota1),
                String.format("%.2f", nota2),
                String.format("%.2f", nota3),
                String.format("%.2f", definitiva),
                estado
            });

            // 7. Limpiar campos
            limpiarFormulario();

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Asegúrese de ingresar solo valores numéricos válidos en las notas.", "Error de formato", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnCalcularActionPerformed
    private void limpiarFormulario() {
        txtCodigo.setText("");
        txtNombre.setText("");
        txtNota1.setText("");
        txtNota2.setText("");
        txtNota3.setText("");
        txtCodigo.requestFocus(); // Devuelve el cursor al campo código
    }

